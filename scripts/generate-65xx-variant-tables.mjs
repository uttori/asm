import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const sourcePath = process.argv[2];
const outputPath = process.argv[3];
const sourceCommit = process.argv[4];
if (!sourcePath || !outputPath || !sourceCommit) {
  throw new Error(
    "Usage: node generate-65xx-variant-tables.mjs <instr.c> <output.ts> <cc65-commit>",
  );
}

const source = fs.readFileSync(sourcePath, "utf8");
const tableNames = [
  ["6502DTV", "6502DTV"],
  ["65SC02", "65SC02"],
  ["65C02", "65C02"],
  ["W65C02", "W65C02"],
  ["65CE02", "65CE02"],
  ["4510", "4510"],
  ["45GS02", "45GS02"],
  ["HuC6280", "HuC6280"],
  ["M740", "m740"],
];

function extractInstructionTable(name, sourceName) {
  const start = source.indexOf(`} InsTab${sourceName} = {`);
  if (start < 0) throw new Error(`Unable to find InsTab${sourceName}.`);
  const end = source.indexOf("/* END SORTED.SH */", start);
  if (end < 0) throw new Error(`Unable to find the end of InsTab${name}.`);
  const rows = [];
  const rowPattern =
    /\{\s*"([A-Z0-9]+)",\s*(0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+),\s*(\d+),\s*([A-Za-z0-9_]+)\s*\}/g;
  for (const match of source.slice(start, end).matchAll(rowPattern)) {
    rows.push([match[1], Number(match[2]), Number(match[3]), Number(match[4]), match[5]]);
  }
  if (rows.length === 0) throw new Error(`InsTab${name} contained no instruction rows.`);
  return rows;
}

const eaStart = source.indexOf("static unsigned char EATab[16][AM65I_COUNT]");
const eaEnd = source.indexOf("/* Table to build the effective SWEET16", eaStart);
if (eaStart < 0 || eaEnd < 0) throw new Error("Unable to find EATab.");
const eaBody = source.slice(eaStart, eaEnd).replace(/\/\*[\s\S]*?\*\//g, "");
const eaRows = [];
for (const match of eaBody.matchAll(/\{([^{}]+)\}/g)) {
  const values = [...match[1].matchAll(/0x[0-9A-Fa-f]+/g)].map(([value]) => Number(value));
  if (values.length === 32) eaRows.push(values);
}
if (eaRows.length !== 16) throw new Error(`Expected 16 EATab rows, got ${eaRows.length}.`);

const tables = Object.fromEntries(
  tableNames.map(([name, sourceName]) => [name, extractInstructionTable(name, sourceName)]),
);
const digest = crypto.createHash("sha256").update(source).digest("hex");
const eaSource = `[\n${eaRows.map((row) => `  [${row.join(", ")}]`).join(",\n")}\n]`;
const tableSource = `{\n${Object.entries(tables)
  .map(
    ([name, rows]) =>
      `  ${JSON.stringify(name)}: [\n${rows.map((row) => `    ${JSON.stringify(row)}`).join(",\n")}\n  ]`,
  )
  .join(",\n")}\n}`;
const generated =
  `// Generated by scripts/generate-65xx-variant-tables.mjs. Do not edit by hand.\n` +
  `// Source: https://github.com/cc65/cc65/blob/master/src/ca65/instr.c\n` +
  `// Commit: ${sourceCommit}\n` +
  `// Source SHA-256: ${digest}\n\n` +
  `export type Ca65Handler = "PutAll" | "PutBitBranch" | "PutBitBranch_m740" | "PutBlockTransfer" | "PutLDM_m740" | "PutPCRel8" | "PutPCRel4510" | "Put4510" | "Put45GS02" | "Put45GS02_Q" | "PutJMP" | "PutJSR_m740" | "PutTAMn" | "PutTMA" | "PutTMAn" | "PutTST";\n` +
  `export type Ca65InstructionRow = readonly [mnemonic: string, modes: number, base: number, eaTable: number, handler: Ca65Handler];\n\n` +
  `export const ca65EaTable: readonly (readonly number[])[] = ${eaSource};\n\n` +
  `export const ca65VariantTables = ${tableSource} as const satisfies Readonly<Record<string, readonly Ca65InstructionRow[]>>;\n`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, generated);
