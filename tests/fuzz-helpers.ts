/** Default deterministic seed used when a fuzz suite does not provide an override. */
export const DEFAULT_FUZZ_SEED = 0x5eeda11;

/** JSON values produced by the bounded hostile-input generator. */
export type FuzzJson = null | boolean | number | string | FuzzJson[] | { [key: string]: FuzzJson };

/**
 * Small deterministic pseudo-random generator for reproducible property tests.
 *
 * This is not a security primitive. Its xorshift32 state is intentionally simple so a failing seed
 * behaves identically on every Node host without introducing a property-testing runtime dependency.
 * Every generated collection and string has an explicit bound; raising those bounds changes the CI
 * resource envelope and must be reviewed with the fuzz-test timeout.
 */
export class FuzzRandom {
  #state: number;

  /**
   * Creates a reproducible generator.
   * @param {number} seed Unsigned 32-bit seed. Zero is remapped because xorshift32 cannot leave it.
   */
  constructor(seed: number) {
    this.#state = seed >>> 0 || DEFAULT_FUZZ_SEED;
  }

  /**
   * Returns the next unsigned 32-bit value.
   * @returns {number} Deterministic unsigned integer.
   */
  nextUint32(): number {
    let value = this.#state;
    value ^= value << 13;
    value ^= value >>> 17;
    value ^= value << 5;
    this.#state = value >>> 0;
    return this.#state;
  }

  /**
   * Selects an integer in `[0, maximum)` without creating an unbounded collection.
   * @param {number} maximum Exclusive positive upper bound.
   * @returns {number} Deterministic bounded integer.
   */
  integer(maximum: number): number {
    if (!Number.isSafeInteger(maximum) || maximum <= 0) {
      throw new Error("Fuzz integer maximum must be a positive safe integer.");
    }
    return this.nextUint32() % maximum;
  }

  /** @returns {boolean} Deterministic boolean. */
  boolean(): boolean {
    return (this.nextUint32() & 1) === 1;
  }

  /**
   * Selects one entry from a non-empty tuple or array.
   * @template T
   * @param {readonly T[]} values Candidate values.
   * @returns {T} Selected value.
   */
  pick<T>(values: readonly T[]): T {
    if (values.length === 0) throw new Error("Fuzz selection requires at least one value.");
    return values[this.integer(values.length)];
  }

  /**
   * Produces a bounded byte array.
   * @param {number} maximumLength Inclusive maximum length.
   * @returns {Uint8Array} Generated bytes.
   */
  bytes(maximumLength: number): Uint8Array {
    const bytes = new Uint8Array(this.integer(maximumLength + 1));
    for (let index = 0; index < bytes.length; index++) bytes[index] = this.integer(0x100);
    return bytes;
  }

  /**
   * Produces bounded JSON-compatible hostile input.
   *
   * Recursion, key counts, array lengths, and string lengths are deliberately capped. Parser fuzzing
   * should explore shapes and boundary values without letting one seed turn into a memory stress test.
   * @param {number} depth Current recursion depth.
   * @returns {FuzzJson} JSON-compatible value with no cycles or exotic prototypes.
   */
  json(depth = 0): FuzzJson {
    const leaf = (): null | boolean | number | string => {
      switch (this.integer(4)) {
        case 0:
          return null;
        case 1:
          return this.boolean();
        case 2:
          return this.pick([
            -1,
            0,
            1,
            255,
            65_535,
            Number.MAX_SAFE_INTEGER,
            -Number.MAX_SAFE_INTEGER,
          ]);
        default: {
          const alphabet = "aA09._:/-\\u0000";
          return Array.from(
            { length: this.integer(17) },
            () => alphabet[this.integer(alphabet.length)],
          ).join("");
        }
      }
    };
    if (depth >= 3 || this.integer(3) === 0) return leaf();
    if (this.boolean()) {
      return Array.from({ length: this.integer(7) }, () => this.json(depth + 1));
    }
    const result: Record<string, FuzzJson> = {};
    for (let index = 0; index < this.integer(7); index++) {
      result[`k${index}_${this.integer(17)}`] = this.json(depth + 1);
    }
    return result;
  }
}

/**
 * Resolves the optional replay seed shared by every deterministic fuzz suite.
 * @param {number} fallback Suite-specific default seed.
 * @returns {number} Unsigned seed selected from `UTTORI_FUZZ_SEED` or the fallback.
 */
export const fuzzSeed = (fallback = DEFAULT_FUZZ_SEED): number => {
  const configured = process.env.UTTORI_FUZZ_SEED;
  if (configured === undefined || configured === "") return fallback >>> 0;
  const parsed = Number(configured);
  if (!Number.isSafeInteger(parsed) || parsed < 0 || parsed > 0xffff_ffff) {
    throw new Error("UTTORI_FUZZ_SEED must be an unsigned 32-bit integer.");
  }
  return parsed >>> 0;
};
