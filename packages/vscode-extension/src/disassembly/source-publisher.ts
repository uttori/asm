import { randomUUID } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

import {
  acquireFileLease,
  durableReplace,
  openAnalysisProjectStore,
  analysisProjectRevision,
  optionalFileHash,
  loadSourceExportManifest,
  validateSourceExportFiles,
  validateSourceExportInputs,
  publishSourceGeneration,
  recoverSourceGeneration,
  type SourcePublicationState,
} from "@uttori/asm-disassembler";
import { NodePluginLoader } from "@uttori/asm-plugin-loader-node";
import snesPlugin, {
  exportSnesProject,
  verifySnesProjectRoundTrip,
  type ExportSnesProjectResult,
  type VerifySnesProjectRoundTripResult,
} from "@uttori/asm-plugin-snes";

import { acquireEditLease, metadataRefreshEligible } from "./edit-coordinator.js";
import type { ResolvedTarget } from "./maintenance-data.js";

/** Verified publication result. Build artifacts remain in the retained candidate tree. */
export interface PublishedSource {
  readonly exported: ExportSnesProjectResult;
  readonly verified: VerifySnesProjectRoundTripResult;
  readonly publication: SourcePublicationState;
}

/** Clone bounded source inputs without copying the database/captures or following symlinks.
 * Stages are siblings so relative trusted plugin paths retain their original meaning.
 * @param {string} root Visible source directory.
 * @param {string} project Native database directory excluded from publication.
 * @param {string} suffix Human-readable retained generation role.
 * @returns {{ directory: string; hashes: Map<string, string | null> }} Copy and exact consumed input inventory.
 */
function stageSource(
  root: string,
  project: string,
  suffix: string,
): { directory: string; hashes: Map<string, string | null> } {
  const directory = fs.mkdtempSync(
    path.join(path.dirname(root), `.${path.basename(root)}-${suffix}-`),
  );
  const hashes = new Map<string, string | null>();
  let size = 0;
  const visit = (relative: string): void => {
    for (const item of fs.readdirSync(path.join(root, relative), { withFileTypes: true })) {
      const name = path.join(relative, item.name);
      const source = path.join(root, name);
      if (
        path.resolve(source) === path.resolve(project) ||
        ["captures", "build", ".git", "node_modules", ".editing"].includes(item.name) ||
        item.name.startsWith(".uttori-publication")
      ) {
        continue;
      }
      if (item.isSymbolicLink() || (!item.isDirectory() && !item.isFile())) {
        throw new Error(`Source staging requires regular files: ${source}`);
      }
      if (item.isDirectory()) {
        fs.mkdirSync(path.join(directory, name), { recursive: true });
        visit(name);
      } else {
        size += fs.statSync(source).size;
        if (size > 1024 ** 3) {
          throw new Error(
            "Source staging exceeds 1 GiB; move unrelated files outside the source export.",
          );
        }
        hashes.set(name, optionalFileHash(source));
        fs.copyFileSync(source, path.join(directory, name));
        if (optionalFileHash(path.join(directory, name)) !== hashes.get(name)) {
          throw new Error(`Source changed while being staged: ${name}`);
        }
      }
    }
  };
  try {
    visit("");
    // Presence of optional interpretation inputs matters even when they were originally absent.
    for (const name of ["ram-map.json", "struct-map.json", "asset-includes.json"]) {
      if (!hashes.has(name)) {
        hashes.set(name, null);
      }
    }
    return { directory, hashes };
  } catch (error) {
    fs.rmSync(directory, { recursive: true, force: true });
    throw error;
  }
}

/** Decide once for all pending metadata edits, with independent map/input drift protection.
 * @param {ResolvedTarget} target Selected native project and source.
 * @returns {boolean} False for unknown writes, classification/seed changes, or changed map inputs.
 */
export function canRefreshMetadata(target: ResolvedTarget): boolean {
  try {
    validateSourceExportInputs(target.sourceDirectory);
    const store = openAnalysisProjectStore(target.projectDirectory);
    try {
      const revision = store.transaction(
        () => analysisProjectRevision(store.manifest()).manifestSha256,
        false,
      );
      if (revision === target.sourceManifest.sourceProjectSha256) {
        return false;
      }
      for (const name of ["ram-map.json", "struct-map.json", "asset-includes.json"]) {
        if (
          fs.existsSync(path.join(target.sourceDirectory, name)) &&
          !target.sourceManifest.inputs?.some((input) => input.path === name)
        ) {
          return false;
        }
      }
      return metadataRefreshEligible(
        target.projectDirectory,
        target.sourceManifest.sourceProjectSha256,
        revision,
      );
    } finally {
      store.close();
    }
  } catch {
    return false;
  }
}

/** Stage, assemble, compare, recheck and journal publication under a per-project lease.
 * Previous generated bytes are also verified before becoming recovery data. Input freshness
 * is deliberately waived only for this historical verification, never byte comparison.
 * @param {ResolvedTarget} target Existing export and exact original ROM.
 * @param {AbortSignal} signal Cancellation before publication; recovery handles process death during it.
 * @param {(message: string) => void} progress Worker stage reporting.
 * @param {string} [expectedRevision] Optional legacy reviewed revision; rejects intervening writes.
 * @returns {Promise<PublishedSource>} Only returned after a durable verified publication.
 */
export async function publishVerifiedSource(
  target: ResolvedTarget,
  signal: AbortSignal,
  progress: (message: string) => void,
  expectedRevision?: string,
): Promise<PublishedSource> {
  const lease = acquireEditLease(target.projectDirectory);
  const loader = new NodePluginLoader();
  let sourceLease: ReturnType<typeof acquireFileLease> | undefined;
  const operationId = randomUUID();
  const journal = path.join(
    target.projectDirectory,
    ".editing",
    "publications",
    `${operationId}.json`,
  );
  let previousDirectory: string | undefined;
  let candidateDirectory: string | undefined;
  const record = (phase: string, details: object = {}): void => {
    durableReplace(
      journal,
      JSON.stringify({
        operationId,
        sourceDirectory: target.sourceDirectory,
        phase,
        updatedAt: new Date().toISOString(),
        previousDirectory,
        candidateDirectory,
        ...details,
      }),
    );
  };
  try {
    sourceLease = acquireFileLease(path.join(target.sourceDirectory, ".uttori-publication.lock"));
    recoverSourceGeneration(target.sourceDirectory);
    record("preparing");
    const manifest = loadSourceExportManifest(target.sourceDirectory);
    validateSourceExportFiles(target.sourceDirectory, manifest);
    progress("Retaining and verifying the previous generation…");
    const previous = stageSource(target.sourceDirectory, target.projectDirectory, "previous");
    previousDirectory = previous.directory;
    record("verifying-previous");
    const verify = (sourceDirectory: string, retainedGeneration = false) =>
      verifySnesProjectRoundTrip({
        sourceDirectory,
        romFile: target.romFile,
        signal,
        retainedGeneration,
        onProgress: ({ message }) => progress(message),
        loadEnvironment: (configFile) =>
          loader.loadProjectEnvironment({
            cwd: sourceDirectory,
            configFile,
            bundledPlugins: new Map([["@uttori/asm-plugin-snes", snesPlugin]]),
          }),
      });
    await verify(previous.directory, true);
    record("previous-verified");
    signal.throwIfAborted();
    progress("Staging the candidate source generation…");
    const candidate = stageSource(target.sourceDirectory, target.projectDirectory, "candidate");
    candidateDirectory = candidate.directory;
    record("generating");
    const exported = exportSnesProject({
      ...target,
      sourceDirectory: candidate.directory,
      signal,
      expectedRevision,
    });
    progress("Verifying candidate ROM bytes before publication…");
    record("verifying-candidate");
    const verified = await verify(candidate.directory);
    record("candidate-verified", {
      revision: exported.manifest.sourceProjectSha256,
      romSha256: verified.comparison.actualSha256,
    });
    signal.throwIfAborted();
    const store = openAnalysisProjectStore(target.projectDirectory);
    try {
      // Hold a SQLite write transaction through publication to exclude legacy/import writers
      // that do not participate in the editor lease. No database content changes here.
      const publication = store.transaction(() => {
        const currentRevision = analysisProjectRevision(store.manifest()).manifestSha256;
        if (currentRevision !== exported.manifest.sourceProjectSha256) {
          throw new Error(
            "Analysis changed during staging. Visible source was preserved; regenerate again.",
          );
        }
        for (const [name, expectedDigest] of candidate.hashes) {
          const actualDigest = optionalFileHash(path.join(target.sourceDirectory, name));
          if (actualDigest !== expectedDigest) {
            throw new Error(
              `Source input changed during staging: ${name}. Visible source was preserved.`,
            );
          }
        }
        progress("Publishing the verified generation with a recovery journal…");
        return publishSourceGeneration(
          target.sourceDirectory,
          previous.directory,
          candidate.directory,
          verified.comparison.actualSha256,
        );
      });
      record("published", {
        publicationId: publication.id,
        revision: publication.revision,
        romSha256: publication.romSha256,
      });
      return {
        exported: { ...exported, sourceDirectory: target.sourceDirectory },
        verified,
        publication,
      };
    } finally {
      store.close();
    }
  } catch (error) {
    record("failed", {
      error: String(error),
      recovery:
        "Inspect the source publication marker before retrying; retained generations are listed here.",
    });
    throw error;
  } finally {
    try {
      await loader.dispose();
    } finally {
      sourceLease?.release();
      lease.release();
    }
  }
}
