/** Pure ownership/status projection. VS Code and database access are supplied by the caller. */
import fs from "node:fs";
import path from "node:path";

import {
  analysisProjectRevision,
  findManagedSourceFile,
  loadSourceOwnership,
  sourceOwnersAt,
  sourceExportSha256,
  type AnalysisProjectManifest,
  type ManagedSourceFile,
  type SourceOwnershipEntry,
  type SourceOwnershipMap,
} from "@uttori/asm-disassembler";

import { informationHex } from "../editor-info/format.js";

/** Authoritative manifest read by the existing analysis worker, never an unverified watcher pointer. */
export interface OwnershipProject {
  readonly directory: string;
  readonly manifest: AnalysisProjectManifest;
}

/** Inspection result separates saved metadata, generated bytes and unverified build output. */
export interface DisassemblyOwnership {
  readonly managed: ManagedSourceFile;
  readonly project?: OwnershipProject;
  readonly candidates: readonly OwnershipProject[];
  readonly owners: readonly SourceOwnershipEntry[];
  readonly sourceStatus: "unchanged" | "changed" | "unsaved";
  readonly generationStatus: "current" | "pending" | "unknown";
  readonly inputChanges: readonly string[];
  readonly ownershipAvailable: boolean;
  readonly canAnnotate: boolean;
}

/**
 * Prefer the colocated analysis project, then an unambiguous producing revision/ROM match.
 * @param {ManagedSourceFile} managed Source membership and original generation identity.
 * @param {readonly OwnershipProject[]} projects Available authoritative manifests from the analysis worker.
 * @returns {{ project?: OwnershipProject; candidates: readonly OwnershipProject[] }} Chosen project when unambiguous, plus matching candidates for diagnostics.
 */
export const owningProject = (
  managed: ManagedSourceFile,
  projects: readonly OwnershipProject[],
): {
  project?: OwnershipProject;
  candidates: readonly OwnershipProject[];
} => {
  const candidates = projects.filter(
    ({ manifest }) =>
      manifest.target === managed.manifest.target &&
      manifest.mapping.mapper === managed.manifest.mapper &&
      manifest.rom.contentSha256 === managed.manifest.rom.contentSha256,
  );
  const colocated = candidates.filter(
    ({ directory }) => path.resolve(directory) === path.join(managed.directory, "analysis"),
  );
  if (colocated.length === 1) {
    return { project: colocated[0], candidates };
  }
  const current = candidates.filter(
    ({ manifest }) =>
      analysisProjectRevision(manifest).manifestSha256 === managed.manifest.sourceProjectSha256,
  );
  if (current.length === 1) {
    return { project: current[0], candidates };
  }
  if (candidates.length === 1) {
    return { project: candidates[0], candidates };
  }
  return { candidates };
};

/**
 * Cache export snapshots between cursor moves. Watchers invalidate this cache on source/input/
 * manifest changes; source bytes are still fingerprinted against the exact editor snapshot.
 */
export class DisassemblyOwnershipResolver {
  readonly #maps = new Map<
    string,
    { managed: ManagedSourceFile; map?: SourceOwnershipMap; inputChanges: string[] }
  >();

  /** Drop every derived snapshot after a relevant filesystem or project publication event. */
  invalidate(): void {
    this.#maps.clear();
  }

  /**
   * Returns undefined for user-owned files; invalid manifests/maps throw instead of granting edits.
   * @param {string} file Absolute source file path.
   * @param {string} text Current editor snapshot, including unsaved changes.
   * @param {number} line One-based selected line.
   * @param {number} column Zero-based character offset.
   * @param {boolean} dirty Whether the editor has unsaved changes.
   * @param {readonly OwnershipProject[]} projects Authoritative manifests of discoverable analysis projects.
   * @returns {DisassemblyOwnership | undefined} Guarded ownership/status, or undefined for user-owned source.
   */
  resolve(
    file: string,
    text: string,
    line: number,
    column: number,
    dirty: boolean,
    projects: readonly OwnershipProject[],
  ): DisassemblyOwnership | undefined {
    let cached = this.#maps.get(file);
    if (!cached) {
      const managed = findManagedSourceFile(file);
      if (!managed) {
        return undefined;
      }
      const inputChanges = (managed.manifest.inputs ?? [])
        .filter((input) => {
          try {
            return (
              sourceExportSha256(fs.readFileSync(path.join(managed.directory, input.path))) !==
              input.sha256
            );
          } catch {
            return true;
          }
        })
        .map(({ path: input }) => input);
      cached = { managed, map: loadSourceOwnership(managed), inputChanges };
      // Bound retained generations in workspaces containing many exports.
      if (this.#maps.size >= 16) {
        this.#maps.clear();
      }
      this.#maps.set(file, cached);
    }
    const { managed, map, inputChanges } = cached;
    const expected = managed.manifest.files.find((entry) => entry.path === managed.relative)!;
    let sourceStatus: DisassemblyOwnership["sourceStatus"] = "unchanged";
    if (dirty) {
      sourceStatus = "unsaved";
    } else if (sourceExportSha256(text) !== expected.sha256) {
      sourceStatus = "changed";
    }
    const { project, candidates } = owningProject(managed, projects);
    let generationStatus: DisassemblyOwnership["generationStatus"] = "unknown";
    if (project) {
      generationStatus =
        analysisProjectRevision(project.manifest).manifestSha256 ===
          managed.manifest.sourceProjectSha256 && !inputChanges.length
          ? "current"
          : "pending";
    }
    // Never attach an old line map to edited text, even if the symbol spelling still looks familiar.
    const owners =
      map && sourceStatus === "unchanged"
        ? sourceOwnersAt(map, managed.relative, text, line, column)
        : [];
    const canAnnotate =
      Boolean(project) &&
      owners.some((owner) => ["label", "function", "instruction", "data"].includes(owner.kind));
    return {
      managed,
      project,
      candidates,
      owners,
      sourceStatus,
      generationStatus,
      inputChanges,
      ownershipAvailable: Boolean(map),
      canAnnotate,
    };
  }
}

/**
 * Compact honest status: this is source freshness, never a claim that a build was verified.
 * @param {DisassemblyOwnership} result Ownership and generation facts for the selected source.
 * @returns {string} Short status for a source hover or status bar.
 */
export const ownershipStatus = (result: DisassemblyOwnership): string => {
  if (result.sourceStatus === "unsaved") {
    return "Generated source: unsaved edits";
  }
  if (result.sourceStatus === "changed") {
    return "Generated source: external changes";
  }
  if (!result.project) {
    return "Generated source: project unresolved";
  }
  if (result.generationStatus === "pending") {
    return "Metadata saved · regeneration pending";
  }
  if (!result.ownershipAvailable) {
    return "Generated source: ownership map unavailable";
  }
  return "Generated source: current";
};

/**
 * Readable, untrusted-data-safe inspector text. Command links are supplied separately by the UI.
 * @param {DisassemblyOwnership} result Resolved source facts for one inspection snapshot.
 * @returns {string} Plain text report; the renderer must escape it for its display surface.
 */
export const ownershipReport = (result: DisassemblyOwnership): string => {
  const lines = [
    ownershipStatus(result),
    "",
    `Source: ${path.join(result.managed.directory, result.managed.relative)}`,
    `Analysis project: ${result.project?.directory ?? "No unique matching project"}`,
    `Saved revision: ${result.project ? analysisProjectRevision(result.project.manifest).manifestSha256 : "unavailable"}`,
    `Generated revision: ${result.managed.manifest.sourceProjectSha256}`,
    `Original ROM SHA-256: ${result.managed.manifest.rom.contentSha256}`,
    "Build / ROM verification: not checked by this inspector.",
    "Integrity: this source and ownership map only; use Show Disassembly Update Status for all generated files.",
  ];
  if (result.inputChanges.length) {
    lines.push(`Changed inputs: ${result.inputChanges.join(", ")}`);
  }
  for (const owner of result.owners) {
    lines.push(
      "",
      `${owner.kind}: ${owner.name ?? owner.symbol ?? owner.id}`,
      `Owner ID: ${owner.id}`,
    );
    if (owner.symbol) {
      lines.push(`Emitted symbol: ${owner.symbol}`);
    }
    if (owner.inputPath) {
      lines.push(`Owning input: ${owner.inputPath}`);
    }
    if (owner.address !== undefined) {
      lines.push(`Native address: ${owner.addressSpace} ${informationHex(owner.address, 6)}`);
    }
    if (owner.emittedAddress !== undefined) {
      lines.push(`Emitted CPU address: ${informationHex(owner.emittedAddress, 6)}`);
    }
    if (owner.outputStart !== undefined) {
      lines.push(
        `Headerless ROM interval: [${informationHex(owner.outputStart, 6)}, ${informationHex(owner.outputEnd!, 6)})`,
      );
    }
    if (owner.evidence?.length) {
      lines.push(`Evidence: ${owner.evidence.join(", ")}`);
    }
  }
  if (!result.ownershipAvailable) {
    lines.push(
      "",
      "Regenerate disassembly to add export-time ownership metadata. Existing annotation editing can use a matching debug map.",
    );
  }
  if (result.sourceStatus !== "unchanged") {
    lines.push(
      "",
      "Preserve these source edits before restoring or regenerating. Exact owner actions are disabled while the source differs.",
    );
  }
  if (!result.owners.length && result.sourceStatus === "unchanged") {
    lines.push(
      "",
      "No editable entity is mapped at this cursor. Move to a definition, operand, or data field.",
    );
  }
  return lines.join("\n");
};
