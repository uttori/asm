import fs from "node:fs";
import path from "node:path";

import {
  loadAnalysisProjectSnapshot,
  sourceExportSha256,
  validateSourceExportFiles,
} from "@uttori/asm-disassembler";
import {
  createRomModificationProject,
  reviewSourceEdit,
  loadRomModificationProject,
  buildModifiedRom,
  type SourceEditReview,
} from "@uttori/asm-plugin-snes";

import { test } from "../../../../tests/ava-helper.js";
import { ownershipFixture } from "../../../../tests/helpers/ownership-fixture.js";
import { importReviewedSource } from "../../src/disassembly/source-import.js";

const fixture = async () => {
  const f = ownershipFixture();
  const manifestFile = await createRomModificationProject({
    sourceDirectory: f.sourceDirectory,
    romFile: f.romFile,
    directory: path.join(f.directory, "modifications"),
  });
  const target = {
    projectDirectory: f.projectDirectory,
    sourceDirectory: f.sourceDirectory,
    romFile: f.romFile,
    sourceManifest: f.manifest,
  };
  return { ...f, manifestFile, target };
};

test("reviewed source label deletion commits native suppression, regenerates and resumes idempotently", async (t) => {
  const f = await fixture();
  t.teardown(f.cleanup);
  fs.writeFileSync(f.file, f.text.replace("L_Item_Price_Candy:\n", ""));
  const reviewFile = reviewSourceEdit({ manifestFile: f.manifestFile, sourceFile: f.file });
  const reviewSha256 = sourceExportSha256(fs.readFileSync(reviewFile));
  const result = await importReviewedSource({ reviewFile, reviewSha256, target: f.target });
  t.regex(result, /regenerated and ROM verified/);
  t.true(loadAnalysisProjectSnapshot(f.projectDirectory).shards.labels[0].suppressed);
  validateSourceExportFiles(f.sourceDirectory);
  t.false(fs.readFileSync(f.file, "utf8").includes("L_Item_Price_Candy:"));
  t.regex(
    await importReviewedSource({ reviewFile, reviewSha256, target: f.target }),
    /already imported/,
  );
});

test("bounded source data edit becomes an owned replacement and restores the exact generated bytes", async (t) => {
  const f = await fixture();
  t.teardown(f.cleanup);
  const lines = f.text.split("\n");
  const index = lines.findIndex((line) => line.includes("raw-000000-00001f.bin"));
  t.true(index >= 0);
  lines[index] = "  db $34, " + new Array(31).fill("$12").join(", ");
  fs.writeFileSync(f.file, lines.join("\n"));
  const reviewFile = reviewSourceEdit({ manifestFile: f.manifestFile, sourceFile: f.file });
  const review = JSON.parse(fs.readFileSync(reviewFile, "utf8")) as SourceEditReview;
  t.falsy(review.unsupported);
  t.truthy(review.replacement);
  await importReviewedSource({
    reviewFile,
    reviewSha256: sourceExportSha256(fs.readFileSync(reviewFile)),
    target: f.target,
  });
  t.is(fs.readFileSync(f.file, "utf8"), f.text);
  validateSourceExportFiles(f.sourceDirectory);
  t.is(loadRomModificationProject(f.manifestFile).replacements.length, 1);
  const build = await buildModifiedRom({ manifestFile: f.manifestFile });
  t.is(fs.readFileSync(build.outputPath)[review.replacement!.offset], 0x34);
});

test("new external changes block import and preserve both drafts and latest source", async (t) => {
  const f = await fixture();
  t.teardown(f.cleanup);
  fs.writeFileSync(f.file, f.text.replace("L_Item_Price_Candy:\n", ""));
  const reviewFile = reviewSourceEdit({ manifestFile: f.manifestFile, sourceFile: f.file });
  const current = fs.readFileSync(f.file, "utf8") + "; newer edit\n";
  fs.writeFileSync(f.file, current);
  await t.throwsAsync(
    importReviewedSource({
      reviewFile,
      reviewSha256: sourceExportSha256(fs.readFileSync(reviewFile)),
      target: f.target,
    }),
    { message: /Source changed after review/ },
  );
  t.is(fs.readFileSync(f.file, "utf8"), current);
  t.falsy(loadAnalysisProjectSnapshot(f.projectDirectory).shards.labels[0].suppressed);
});
